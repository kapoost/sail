"""What changes between the two language versions, and what deliberately does not.

The English page is the original and lives at the root; the Polish one lives under
`/pl/`. Everything that is *prose* is translated. Three things are not, and each for a
reason worth stating rather than discovering:

* **The key list.** It is generated from `crates/sail-app/src/help.rs`, which is the
  program's own help screen, and the program is in English. A translated key list would
  be a second copy of that list — the exact thing this site was built to avoid — and it
  would go stale the first time somebody edits the help and does not also edit a
  dictionary here. It is also what a player sees on screen when they press `?`.

* **The polar.** Generated output, with column headings a sailor reads the same way in
  any language.

* **The model table.** It comes out of `README.md`, which is English because the
  repository is.

So the Polish page is a Polish text wrapped round English artefacts, and says so where
a reader would otherwise wonder.
"""

